"""Start a Streamlit UI, rendering its OIDC login secrets from the environment first.

Usage::

    python -m app.ui_launcher {playground|admin} [--port N] [--address A] [-- streamlit args]

Streamlit reads OIDC settings only from ``.streamlit/secrets.toml``, and registers its
login routes when it starts, so the file must exist *before* the server process does.
This launcher therefore turns the cloud-agnostic ``AUTH_*`` / ``OIDC_*`` variables into
that file and then replaces itself with ``streamlit run`` -- the one place that knows how
to start a UI, shared by docker-compose, the Azure Container Apps definitions and the
local no-Docker script.

When ``AUTH_ENABLED`` is off nothing is generated and Streamlit starts exactly as before.
The generated file carries a marker header: the launcher refuses to overwrite a secrets
file it did not create, and only ever deletes its own.
"""

from __future__ import annotations

import argparse
import contextlib
import os
import shutil
import sys
import tempfile
from collections.abc import Callable, Sequence
from pathlib import Path

from app.auth_settings import AuthConfigError, AuthSettings, load_auth_settings

TARGETS = {
    "playground": ("app/streamlit_app.py", 7860),
    "admin": ("app/streamlit_admin.py", 7861),
}
GENERATED_MARKER = "# Generated by app.ui_launcher from AUTH_*/OIDC_* environment variables."
SECRETS_RELATIVE_PATH = Path(".streamlit") / "secrets.toml"


class SecretsFileConflict(RuntimeError):
    """An existing secrets.toml was not generated by this launcher."""


def toml_string(value: str) -> str:
    """Encode ``value`` as a TOML basic string."""
    escapes = {'"': '\\"', "\\": "\\\\", "\n": "\\n", "\r": "\\r", "\t": "\\t", "\b": "\\b", "\f": "\\f"}
    out = []
    for char in value:
        if char in escapes:
            out.append(escapes[char])
        elif ord(char) < 0x20 or ord(char) == 0x7F:
            out.append(f"\\u{ord(char):04x}")
        else:
            out.append(char)
    return '"' + "".join(out) + '"'


def render_secrets(settings: AuthSettings) -> str:
    """Render the Streamlit ``[auth]`` table for these settings."""
    client_kwargs = [
        f"scope = {toml_string(settings.scope_string)}",
        # PKCE (RFC 7636) on top of the confidential-client secret.
        'code_challenge_method = "S256"',
    ]
    if settings.prompt:
        client_kwargs.append(f"prompt = {toml_string(settings.prompt)}")

    lines = [
        GENERATED_MARKER,
        "# Regenerated on every start. Do not edit or commit.",
        "[auth]",
        # The literal "{port}" placeholder (if used) is substituted by Streamlit, which
        # keeps this file identical for every UI started from the same directory.
        f"redirect_uri = {toml_string(settings.redirect_uri)}",
        f"cookie_secret = {toml_string(settings.cookie_secret)}",
        f"client_id = {toml_string(settings.client_id)}",
        f"client_secret = {toml_string(settings.client_secret)}",
        f"server_metadata_url = {toml_string(settings.metadata_url)}",
        # Only the API access token is exposed to the app; the ID token stays internal.
        'expose_tokens = ["access"]',
        "client_kwargs = { " + ", ".join(client_kwargs) + " }",
        "",
    ]
    return "\n".join(lines)


def write_secrets(content: str, path: Path) -> bool:
    """Atomically write ``content`` to ``path`` (mode 0600). Returns True if it changed."""
    path.parent.mkdir(parents=True, exist_ok=True)
    try:
        existing = path.read_text(encoding="utf-8")
    except FileNotFoundError:
        existing = None
    if existing is not None:
        if not existing.startswith(GENERATED_MARKER):
            raise SecretsFileConflict(
                f"{path} already exists and was not generated by app.ui_launcher; "
                "move or delete it so authentication can be configured from the environment."
            )
        if existing == content:
            os.chmod(path, 0o600)
            return False

    # mkstemp creates the file 0600, so the secret is never readable by others.
    fd, tmp_name = tempfile.mkstemp(dir=path.parent, prefix=".secrets-", suffix=".tmp")
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as handle:
            handle.write(content)
            handle.flush()
            os.fsync(handle.fileno())
        os.chmod(tmp_name, 0o600)
        os.replace(tmp_name, path)
    except BaseException:
        with contextlib.suppress(FileNotFoundError):
            os.unlink(tmp_name)
        raise
    return True


def remove_generated_secrets(path: Path) -> bool:
    """Delete a secrets file this launcher generated earlier (never anyone else's)."""
    try:
        existing = path.read_text(encoding="utf-8")
    except FileNotFoundError:
        return False
    if not existing.startswith(GENERATED_MARKER):
        return False
    path.unlink()
    return True


def build_command(target: str, port: int, address: str, extra: Sequence[str] = ()) -> list[str]:
    script, _ = TARGETS[target]
    streamlit = shutil.which("streamlit")
    base = [streamlit] if streamlit else [sys.executable, "-m", "streamlit"]
    return [
        *base,
        "run",
        script,
        "--server.port",
        str(port),
        "--server.address",
        address,
        "--server.headless",
        "true",
        "--client.toolbarMode",
        "minimal",
        *extra,
    ]


def main(
    argv: Sequence[str] | None = None,
    *,
    exec_fn: Callable[[str, list[str]], object] = os.execvp,
    workdir: Path | None = None,
) -> int:
    parser = argparse.ArgumentParser(prog="python -m app.ui_launcher", description=__doc__.split("\n")[0])
    parser.add_argument("target", choices=sorted(TARGETS))
    parser.add_argument("--port", type=int, help="Server port (default: 7860 playground, 7861 admin).")
    parser.add_argument("--address", default="0.0.0.0", help="Bind address (default: 0.0.0.0).")
    args, extra = parser.parse_known_args(argv)
    extra = [a for a in extra if a != "--"]

    port = args.port or TARGETS[args.target][1]
    secrets_path = (workdir or Path.cwd()) / SECRETS_RELATIVE_PATH

    try:
        settings = load_auth_settings("ui")
        if settings.enabled:
            changed = write_secrets(render_secrets(settings), secrets_path)
            print(
                f"[ui_launcher] authentication enabled for {args.target}; "
                f"OIDC secrets {'written to' if changed else 'already current at'} {secrets_path}",
                flush=True,
            )
        elif remove_generated_secrets(secrets_path):
            print(f"[ui_launcher] authentication disabled; removed stale {secrets_path}", flush=True)
    except (AuthConfigError, SecretsFileConflict) as exc:
        print(f"[ui_launcher] {exc}", file=sys.stderr, flush=True)
        return 2

    command = build_command(args.target, port, args.address, extra)
    exec_fn(command[0], command)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
